function showPhoto(src, cap) {
  const scrim = el('div', { class: 'scrim', style: 'align-items:center', onclick: closeSheet },
    el('figure', { class: 'photo-big' }, el('img', { src, alt: cap }), el('figcaption', null, cap)));
  document.getElementById('layer').replaceChildren(scrim);
  document.addEventListener('keydown', escClose);
}
function photoBtn(f, cap) {
  const im = el('img', { alt: cap });
  authBlob('/api/private/img/' + f + '.jpg').then((u) => { im.src = u; }).catch(() => {});
  return el('button', { type: 'button', onclick: () => { if (im.src) showPhoto(im.src, cap); } }, im, el('span', null, cap));
}
function gallery() {
  return el('section', { class: 'week', style: 'gap:16px' },
    el('h2', null, el('span', null, 'Фото для вдохновения')),
    GALLERY.map(([name, photos]) => el('div', { class: 'gal-group' },
      el('p', { class: 'gal-label' }, name),
      el('div', { class: 'gal-grid' }, photos.map(([f, cap]) => photoBtn(f, cap))))));
}

